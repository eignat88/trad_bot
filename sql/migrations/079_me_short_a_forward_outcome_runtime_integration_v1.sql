-- ============================================================
-- Migration 079: ME SHORT A Forward Outcome Runtime Integration V1
-- Issue #208 follow-up —
-- ME_SHORT_A_FORWARD_OUTCOME_RUNTIME_INTEGRATION_V1
-- ============================================================
-- Operational heartbeat / diagnostics storage for the independent
-- observe-only runtime that drives the migration 078 collector.
--
-- WHAT THIS MIGRATION ADDS:
--   * research.me_short_a_forward_outcome_runtime_heartbeat_v1
--       APPEND-ONLY runner heartbeat + diagnostics log. It stores runner
--       lifecycle state and monotonic counters ONLY — no prices, no
--       outcomes, no signal geometry, no research evidence. Its purpose is
--       operational visibility ("is the collector alive and what has it
--       done?"), not measurement.
--   * research.v_me_short_a_forward_outcome_runtime_status_v1
--       the current runner state, derived from the latest heartbeat row
--       together with the (read-only) activation snapshot.
--
-- WHY A LOG INSTEAD OF A MUTABLE STATE ROW:
--   the whole protocol is append-only, so a "current state" is always just
--   the latest row of an immutable log. That gives a complete audit trail
--   of the runner's lifecycle and avoids introducing ANY mutable table that
--   could later be mistaken for evidence.
--
-- IDENTITY:
--   runtime_protocol_hash is recorded on every heartbeat row so an operator
--   can prove which runtime protocol version produced the counters.
--
-- WHAT THIS MIGRATION NEVER DOES:
--   * never writes to research.me_short_a_fill_feasibility_v1 (Phase 1),
--   * never writes to research.prospective_observation /
--     research.prospective_outcome (the closed frozen OOS cohort),
--   * never touches scanner / paper / live / direction-gate state,
--   * never activates anything and never changes freeze_ts,
--   * contains NO data seeding at all (there is deliberately not a single
--     INSERT INTO in this file).
--
-- This migration is source-controlled only. It is NOT applied to
-- production PostgreSQL as part of this task.
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS research;

-- ── 0. Dependency precondition (migration 078) ───────────────

DO $$
BEGIN
    IF to_regclass('research.me_short_a_lineage_activation_v1') IS NULL
       OR to_regclass('research.me_short_a_event_lineage_v1') IS NULL
       OR to_regclass('research.me_short_a_outcome_observation_v1') IS NULL THEN
        RAISE EXCEPTION
            'ME SHORT A forward outcome runtime precondition failed: migration '
            '078 (research.me_short_a_lineage_activation_v1 / '
            'research.me_short_a_event_lineage_v1 / '
            'research.me_short_a_outcome_observation_v1) must be applied first';
    END IF;
END $$;

-- ── 1. Append-only runner heartbeat / diagnostics log ────────
-- Operational metadata only. Counters are monotonic within one runner
-- instance (they are cumulative since `started_at`).

CREATE TABLE IF NOT EXISTS research.me_short_a_forward_outcome_runtime_heartbeat_v1 (
  heartbeat_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  experiment text NOT NULL
    CHECK (experiment = 'ME_SHORT_A_FORWARD_OUTCOME_RUNTIME_INTEGRATION_V1'),
  runtime_protocol_version text NOT NULL
    CHECK (runtime_protocol_version = 'ME_SHORT_A_FORWARD_OUTCOME_RUNTIME_INTEGRATION_V1'),
  runtime_protocol_hash text NOT NULL
    CHECK (runtime_protocol_hash ~ '^[0-9a-f]{64}$'),
  runner_id text NOT NULL CHECK (length(runner_id) BETWEEN 1 AND 200),
  generation bigint NOT NULL DEFAULT 0 CHECK (generation >= 0),
  cycle_id bigint NOT NULL CHECK (cycle_id >= 0),
  runner_state text NOT NULL
    CHECK (runner_state IN ('IDLE','RUNNING','STOPPING','STOPPED','FAILED')),
  lifecycle_phase text NOT NULL CHECK (length(lifecycle_phase) BETWEEN 1 AND 120),
  -- The activation snapshot is READ-ONLY information about the migration 078
  -- collector lifecycle. This runtime never writes it.
  activation_status text
    CHECK (activation_status IS NULL
           OR activation_status IN ('READY_TO_START','RUNNING','COMPLETED','CANCELLED')),
  activation_freeze_ts timestamptz,
  started_at timestamptz NOT NULL,
  observed_at timestamptz NOT NULL,
  cycles_completed bigint NOT NULL DEFAULT 0 CHECK (cycles_completed >= 0),
  candidates_seen bigint NOT NULL DEFAULT 0 CHECK (candidates_seen >= 0),
  signals_captured bigint NOT NULL DEFAULT 0 CHECK (signals_captured >= 0),
  lineages_recorded bigint NOT NULL DEFAULT 0 CHECK (lineages_recorded >= 0),
  candles_captured bigint NOT NULL DEFAULT 0 CHECK (candles_captured >= 0),
  outcomes_finalized bigint NOT NULL DEFAULT 0 CHECK (outcomes_finalized >= 0),
  outcomes_matched bigint NOT NULL DEFAULT 0 CHECK (outcomes_matched >= 0),
  outcomes_incomplete bigint NOT NULL DEFAULT 0 CHECK (outcomes_incomplete >= 0),
  skipped_not_activated bigint NOT NULL DEFAULT 0 CHECK (skipped_not_activated >= 0),
  skipped_pre_freeze bigint NOT NULL DEFAULT 0 CHECK (skipped_pre_freeze >= 0),
  skipped_idempotent bigint NOT NULL DEFAULT 0 CHECK (skipped_idempotent >= 0),
  skipped_invalid_candidate bigint NOT NULL DEFAULT 0
    CHECK (skipped_invalid_candidate >= 0),
  skipped_lookahead bigint NOT NULL DEFAULT 0 CHECK (skipped_lookahead >= 0),
  skipped_unmatured bigint NOT NULL DEFAULT 0 CHECK (skipped_unmatured >= 0),
  errors bigint NOT NULL DEFAULT 0 CHECK (errors >= 0),
  last_event_time timestamptz,
  last_error text CHECK (last_error IS NULL OR length(last_error) <= 2000),
  open_events bigint NOT NULL DEFAULT 0 CHECK (open_events >= 0),
  config_fingerprint text NOT NULL
    CHECK (config_fingerprint ~ '^[0-9a-f]{16}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT me_short_a_runtime_heartbeat_time_order
    CHECK (observed_at >= started_at),
  CONSTRAINT me_short_a_runtime_heartbeat_event_order
    CHECK (last_event_time IS NULL OR last_event_time <= observed_at),
  -- No research values may ever hide in the diagnostics payload.
  CONSTRAINT me_short_a_runtime_heartbeat_no_evidence
    CHECK (outcomes_matched <= outcomes_finalized)
);

CREATE INDEX IF NOT EXISTS idx_me_short_a_runtime_heartbeat_runner
  ON research.me_short_a_forward_outcome_runtime_heartbeat_v1 (runner_id, observed_at DESC);
CREATE INDEX IF NOT EXISTS idx_me_short_a_runtime_heartbeat_observed
  ON research.me_short_a_forward_outcome_runtime_heartbeat_v1 (observed_at DESC);

-- ── 2. Append-only enforcement ───────────────────────────────
-- Same discipline as the capture tables: a heartbeat log that can be
-- rewritten is worthless as a diagnostic trail.

CREATE OR REPLACE FUNCTION research.fn_block_me_short_a_runtime_heartbeat_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $trigger$
BEGIN
    RAISE EXCEPTION
        'ME SHORT A forward outcome runtime heartbeat rows are append-only '
        '(table=%, heartbeat_id=%)',
        TG_TABLE_NAME,
        OLD.heartbeat_id
        USING ERRCODE = 'restrict_violation';
END;
$trigger$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'research.me_short_a_forward_outcome_runtime_heartbeat_v1'::regclass
          AND tgname = 'trg_me_short_a_runtime_heartbeat_block_mutation'
          AND NOT tgisinternal
    ) THEN
        CREATE TRIGGER trg_me_short_a_runtime_heartbeat_block_mutation
        BEFORE UPDATE OR DELETE
        ON research.me_short_a_forward_outcome_runtime_heartbeat_v1
        FOR EACH ROW
        EXECUTE FUNCTION research.fn_block_me_short_a_runtime_heartbeat_mutation();
    END IF;
END $$;

-- ── 3. Current runtime status (derived, never stored) ────────
-- A runner is considered stale when it has not written a heartbeat for more
-- than 300 seconds (5 minutes). The runtime writes one heartbeat per cycle
-- and is designed to idle for at most `idle_sleep_seconds` between cycles,
-- so 300s tolerates a few slow cycles and still catches a crashed runner.

CREATE OR REPLACE VIEW research.v_me_short_a_forward_outcome_runtime_status_v1 AS
WITH latest AS (
    SELECT DISTINCT ON (h.runner_id)
           h.heartbeat_id,
           h.runner_id,
           h.generation,
           h.cycle_id,
           h.runner_state,
           h.lifecycle_phase,
           h.activation_status,
           h.activation_freeze_ts,
           h.started_at,
           h.observed_at,
           h.cycles_completed,
           h.candidates_seen,
           h.signals_captured,
           h.lineages_recorded,
           h.candles_captured,
           h.outcomes_finalized,
           h.outcomes_matched,
           h.outcomes_incomplete,
           h.skipped_not_activated,
           h.skipped_pre_freeze,
           h.skipped_idempotent,
           h.skipped_invalid_candidate,
           h.skipped_lookahead,
           h.skipped_unmatured,
           h.errors,
           h.last_event_time,
           h.last_error,
           h.open_events,
           h.config_fingerprint,
           h.runtime_protocol_hash
      FROM research.me_short_a_forward_outcome_runtime_heartbeat_v1 h
     ORDER BY h.runner_id, h.observed_at DESC, h.heartbeat_id DESC
),
activation AS (
    SELECT a.status, a.freeze_ts
      FROM research.me_short_a_lineage_activation_v1 a
     WHERE a.protocol_version = 'ME_SHORT_A_FORWARD_ONLY_OUTCOME_AND_LINEAGE_CAPTURE_V1'
)
SELECT
    l.runner_id,
    l.generation,
    l.cycle_id,
    l.runner_state,
    l.lifecycle_phase,
    l.runtime_protocol_hash,
    l.config_fingerprint,
    l.started_at,
    l.observed_at                                                    AS last_heartbeat_at,
    EXTRACT(EPOCH FROM (now() - l.observed_at))::bigint               AS heartbeat_age_seconds,
    (EXTRACT(EPOCH FROM (now() - l.observed_at))::bigint > 300)       AS is_stale,
    l.activation_status                                              AS runner_seen_activation_status,
    l.activation_freeze_ts                                           AS runner_seen_freeze_ts,
    a.status                                                         AS activation_status,
    a.freeze_ts,
    (a.status = 'RUNNING' AND a.freeze_ts IS NOT NULL)               AS collector_activated,
    l.cycles_completed,
    l.candidates_seen,
    l.signals_captured,
    l.lineages_recorded,
    l.candles_captured,
    l.outcomes_finalized,
    l.outcomes_matched,
    l.outcomes_incomplete,
    l.skipped_not_activated,
    l.skipped_pre_freeze,
    l.skipped_idempotent,
    l.skipped_invalid_candidate,
    l.skipped_lookahead,
    l.skipped_unmatured,
    l.errors,
    l.last_event_time,
    l.last_error,
    l.open_events
  FROM latest l
  CROSS JOIN activation a;

-- ── 4. Least-privilege: drop inherited broad privileges ──────
-- migrations 049/050 install ALTER DEFAULT PRIVILEGES ... GRANT SELECT,
-- INSERT, UPDATE ON TABLES TO trad_bot for schema research, so the new
-- table would otherwise silently inherit write privileges for the broad
-- runtime role. Remove them before the narrow grants are applied.

DO $$
DECLARE
    rol text;
BEGIN
    FOREACH rol IN ARRAY ARRAY[
        'trad_bot',
        'analytics_agent',
        'analytics_runner',
        'trad_bot_me_short_a_collector',
        'trad_bot_me_short_a_audit'
    ] LOOP
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = rol) THEN
            EXECUTE format(
                'REVOKE ALL ON research.me_short_a_forward_outcome_runtime_heartbeat_v1 FROM %I',
                rol);
        END IF;
    END LOOP;
END $$;

COMMIT;
